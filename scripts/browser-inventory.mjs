import assert from 'node:assert/strict';
import path from 'node:path';

export async function checkInventory({ page, width, artifacts, readSlot, font }) {
  const button = name => page.getByRole('button', { name, exact: true });
  const move = async key => { await page.locator('.map-grid').focus(); await page.clock.runFor(100); await page.keyboard.press(key); };
  const open = async () => {
    await page.getByRole('navigation', { name: '주 메뉴' }).getByRole('button', { name: '소지품', exact: true }).click();
    const panel = width > 760 ? page.getByRole('dialog', { name: '소지품', exact: true }) : page.locator('.tab-page');
    await panel.waitFor(); return panel;
  };
  const close = async () => width > 760 ? button('소지품 닫기').click() : page.getByRole('navigation').getByRole('button', { name: '탐험', exact: true }).click();
  assert.equal(await page.getByRole('gridcell', { name: '폐허의 상자 (5, 3)', exact: true }).count(), 0);
  await move('ArrowRight'); await move('ArrowRight');
  assert.equal(await page.getByTestId('position').textContent(), '(3, 1)');
  const chestButton = button('상자 열기');
  await button('설정').click(); await page.keyboard.press('z'); assert.equal(await page.getByTestId('chest-status').count(), 0);
  await button('닫기').click(); await page.locator('.map-grid').focus();
  if (width === 390) await page.keyboard.press('z'); else if (width === 320) await page.keyboard.press('Space'); else await chestButton.click();
  assert(await chestButton.isDisabled());
  const receipt = await page.getByTestId('chest-status').textContent();
  assert(receipt.includes('상자를 열어 다음 물품을 얻었습니다.')); assert(receipt.includes('여행 식량 ×3')); assert(receipt.includes('탐험용 장화 ×1'));
  assert(!receipt.includes('이미 연 상자입니다.'));
  await page.locator('.map-grid').focus(); await page.keyboard.press('z'); assert.equal(await page.getByTestId('chest-status').textContent(), receipt);
  await page.screenshot({ path: path.join(artifacts, `chest-receipt-${width}.png`), fullPage: true });
  await move('ArrowLeft'); await move('ArrowRight'); assert.equal(await page.getByTestId('chest-status').textContent(), '이미 연 상자입니다.');
  let panel = await open();
  assert((await panel.locator('[data-item-id="item.travel_ration"]').textContent()).includes('×3'));
  assert.equal(await panel.getByTestId('inventory-weight').textContent(), '1550 g'); assert(await panel.getByRole('button', { name: '먹기', exact: true }).isDisabled());
  await page.keyboard.press('ArrowLeft'); await page.keyboard.press('z'); assert.equal(await page.getByTestId('position').textContent(), '(3, 1)');
  await panel.getByRole('button', { name: '탐험용 장화 1개', exact: true }).click(); await panel.getByRole('button', { name: '장착', exact: true }).click();
  assert((await panel.getByTestId('inventory-move-cost').textContent()).includes('미탐사 4 · 탐사 경로 2')); await close();
  for (const key of ['ArrowDown', 'ArrowDown', 'ArrowRight']) await move(key);
  assert.equal(await page.getByTestId('stamina').first().textContent(), '896 / 900');
  panel = await open(); const tick = await page.getByTestId('clock').textContent(); await page.clock.runFor(2000);
  assert.notEqual(await page.getByTestId('clock').textContent(), tick);
  await panel.getByRole('button', { name: '여행 식량 3개', exact: true }).click(); await panel.getByRole('button', { name: '먹기', exact: true }).click();
  assert((await panel.locator('[data-item-id="item.travel_ration"]').textContent()).includes('×2')); assert.equal(await panel.getByTestId('inventory-weight').textContent(), '1300 g');
  await panel.getByRole('button', { name: '탐험용 장화 1개', exact: true }).click(); await panel.getByRole('button', { name: '해제', exact: true }).click();
  assert((await panel.getByTestId('inventory-move-cost').textContent()).includes('미탐사 6 · 탐사 경로 3')); await panel.getByRole('button', { name: '장착', exact: true }).click();
  await font(page); assert(!await panel.evaluate(el => el.scrollWidth > el.clientWidth));
  await page.screenshot({ path: path.join(artifacts, `inventory-${width}.png`), fullPage: true });
  await close(); await button('귀환').click(); await page.clock.runFor(5000);
  const saved = await readSlot(page); assert.equal(saved.schemaVersion, 7); assert.equal(saved.state.character.inventory.equipment.feet, 'item.trail_boots');
  assert.equal(saved.state.character.inventory.stacks['item.travel_ration'], 2); assert.equal(saved.state.campaign.openedChests['chest.camp_supply'], true);
  await page.reload(); await page.getByTestId('position').waitFor(); panel = await open();
  assert((await panel.locator('[data-item-id="item.travel_ration"]').textContent()).includes('×2'));
  assert((await panel.getByTestId('inventory-move-cost').textContent()).includes('미탐사 4 · 탐사 경로 2')); await close();
  await move('ArrowRight'); await move('ArrowRight'); assert(await chestButton.isDisabled()); assert.equal(await page.getByTestId('chest-status').textContent(), '이미 연 상자입니다.');
  return { width, inventoryLootUseEquip: true, lootReceipt: true, interactionShortcut: width === 390 ? 'Z' : width === 320 ? 'Space' : 'button', recoveryWithInventoryOpen: true, persistedInventory: true };
}
